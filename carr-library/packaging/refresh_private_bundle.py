"""Refresh a verified owner's private offline bundle into a directory or ZIP.

Reuse already acquired locked dependencies/models, verify the new application
against its exact Git commit, and copy explicit local audio/citation runtimes.
No downloads, installers, public release, or changes to the original bundle.
"""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import stat
import tempfile
from tempfile import TemporaryDirectory
import zipfile

from build_windows_bundle import (read_lock, wheel_metadata, verify_application_source,
                                  verify_dependency_closure, sha256)
from install_windows import verify
from prepare_windows_audio import load_lock, regular, local, _pe64
from create_delivery import (_read_manifest, _manifest, _name, _file, _stream, _check,
                             _directories, _unchanged_directories, _stamp, _identity,
                             _verify_archive, _publish, PREFIX, MANIFEST, SOURCES,
                             MAX_FILE, MAX_TOTAL)

HERE = Path(__file__).resolve().parent


class _Payload:
    """One verified origin or bounded generated byte string, shared by both outputs."""
    def __init__(self, origin, digest=None, *, error='Bundle payload changed during refresh.'):
        if isinstance(origin, bytes):
            self.origin, self.size = origin, len(origin)
            self.sha256 = hashlib.sha256(origin).hexdigest()
        else:
            self.origin = local(origin, exists=True)
            self.size = regular(self.origin).st_size
            self.sha256 = digest if digest is not None else sha256(self.origin)
        self.error = error

    def write(self, destination, cancelled):
        _check(cancelled)
        if isinstance(self.origin, bytes):
            value, size = _stream(io.BytesIO(self.origin), cancelled, destination=destination, limit=self.size)
        else:
            local(self.origin, exists=True)
            regular(self.origin)
            with _file(self.origin) as stream:
                value, size = _stream(stream, cancelled, destination=destination, limit=self.size)
        if value != self.sha256 or size != self.size:
            raise ValueError(self.error)


def _destination(source, wheel, output):
    source, wheel, output = local(source, exists=True), local(wheel, exists=True), local(output)
    regular(source, directory=True)
    regular(wheel)
    if os.path.lexists(output) or output.is_relative_to(source) or source.is_relative_to(output):
        raise ValueError('Choose a new bundle output outside the previous one.')
    return source, wheel, output


def _plan(source, wheel, source_commit, *, parent_manifest_sha256,
          audio=None, citations=None, extra_wheelhouse=None, cancelled=lambda: False):
    """One validation and file-selection path; never execute supplied payloads."""
    _check(cancelled)
    if (not isinstance(parent_manifest_sha256, str)
            or not re.fullmatch('[0-9a-f]{64}', parent_manifest_sha256)):
        raise ValueError('An independently recorded parent manifest SHA256 is required.')
    raw = _read_manifest(source, cancelled)
    if hashlib.sha256(raw).hexdigest() != parent_manifest_sha256:
        raise ValueError('The parent bundle manifest differs from its recorded SHA256.')
    previous = _manifest(raw, json.loads(raw).get('source_commit'))
    verify(source, manifest_bytes=raw)
    _check(cancelled)
    identity = verify_application_source(wheel, source_commit)
    lock = read_lock(HERE / ('windows-semantic-cp311.lock' if previous.get('bundled_model') else 'windows-cp311.lock'))
    dependencies = {}
    selected = {}
    wheelhouses = [source / 'wheelhouse']
    if extra_wheelhouse is not None:
        wheelhouses.append(local(extra_wheelhouse, exists=True))
    for directory in wheelhouses:
        regular(directory, directory=True)
        for path in directory.iterdir():
            _check(cancelled)
            regular(path)
            if path.suffix != '.whl':
                raise ValueError('A wheelhouse must contain only regular wheel files.')
            name, version, metadata = wheel_metadata(path)
            if name == 'universal-research-library' and directory == wheelhouses[0]:
                continue
            digest = sha256(path)
            if name not in lock or str(version) != lock[name][0] or digest not in lock[name][1]:
                raise ValueError('A dependency does not match the current lock: ' + name)
            if name in dependencies:
                raise ValueError('More than one wheel supplied for dependency: ' + name)
            dependencies[name] = (path, digest)
            selected[name] = (path, version, metadata)
    if set(dependencies) != set(lock):
        raise ValueError('The private bundle and extra wheelhouse lack required locked dependencies.')
    name, version, metadata = wheel_metadata(wheel)
    if name != 'universal-research-library' or name in selected:
        raise ValueError('Expected exactly one application wheel.')
    selected[name] = (wheel, version, metadata)
    verify_dependency_closure(selected)
    sbom_path = HERE / ('windows-semantic-sbom.cdx.json' if previous.get('bundled_model') else 'windows-sbom.cdx.json')
    sbom_bytes = sbom_path.read_bytes()
    sbom = json.loads(sbom_bytes)
    components = sbom.get('components', [])
    if (sbom.get('bomFormat') != 'CycloneDX' or sbom.get('specVersion') != '1.5'
            or len(components) != len(lock)
            or {(item['name'], item['version']) for item in components}
            != {(name, version) for name, (version, _) in lock.items()}):
        raise ValueError('The current runtime SBOM differs from the dependency lock.')
    audio_files = {}
    if audio is not None:
        audio = local(audio, exists=True)
        audio_lock, _ = load_lock(HERE / 'windows-audio.lock.json')
        for name, record in audio_lock['output_files'].items():
            _check(cancelled)
            path = local(audio / name, exists=True)
            if regular(path).st_size != record['size'] or sha256(path) != record['sha256']:
                raise ValueError('Audio runtime differs from the pinned build.')
            if path.suffix == '.exe':
                _pe64(path)
            audio_files[name] = path
    node_files = {}
    if citations is not None:
        citations = local(citations, exists=True)
        node_lock = json.loads((HERE / 'windows-citations.lock.json').read_bytes())
        for name, expected in node_lock['files'].items():
            _check(cancelled)
            path = local(citations / name, exists=True)
            regular(path)
            if sha256(path) != expected:
                raise ValueError('Citation runtime differs from the pinned Node build.')
            node_files[name] = path
        _pe64(node_files['node.exe'])
    payloads = {}
    def add(name, origin, expected=None, error='Bundle payload changed during refresh.'):
        _name(name)
        payloads[name] = _Payload(origin, expected, error=error)
    for name, expected in previous['files'].items():
        _check(cancelled)
        if not name.startswith(('audio/', 'citation-runtime/', 'wheelhouse/')):
            add(name, source / name, expected, 'The old bundle changed during refresh.')
    for path, expected in dependencies.values():
        add('wheelhouse/' + path.name, path, expected,
            'A locked dependency changed during private bundle assembly.')
    add('wheelhouse/' + wheel.name, wheel, identity['wheel_sha256'],
        'Application wheel changed after exact source verification.')
    requirements = []
    for name, (path, version, _) in sorted(selected.items(), key=lambda item: item[1][0].name):
        requirements.append(f'{name}=={version} --hash=sha256:{payloads["wheelhouse/" + path.name].sha256}')
    add('install.lock', ('\n'.join(requirements) + '\n').encode('utf-8'))
    for name in ('install_windows.py', 'Install.cmd', 'ResearchLibrary.cmd', 'CheckInstallation.cmd'):
        add(name, HERE / name)
    add('README.txt', HERE.parent / 'docs' / 'RUNNING.md')
    add('START_V3_UK.txt', HERE.parent / 'docs' / 'START_V3_UK.txt')
    add('runtime-sbom.cdx.json', sbom_bytes)
    for origin in (HERE / 'wheel-notices').iterdir():
        add('notices/wheels/' + origin.name, origin)
    for directory, files in (('audio', audio_files), ('citation-runtime', node_files)):
        for name, origin in files.items():
            expected = (audio_lock['output_files'][name]['sha256'] if directory == 'audio'
                        else node_lock['files'][name])
            add(directory + '/' + name, origin, expected,
                'A local runtime changed during private bundle assembly.')
        if files:
            lock_name = 'windows-audio.lock.json' if directory == 'audio' else 'windows-citations.lock.json'
            add(directory + '/provenance.json', HERE / lock_name)
    add('application-source.json', (json.dumps(identity, indent=2) + '\n').encode('utf-8'))
    manifest = {key: value for key, value in previous.items() if key not in ('files', 'source_commit')}
    manifest.update(source_commit=source_commit, bundled_audio=bool(audio_files),
                    bundled_citation_runtime=bool(node_files), use_scope='private-personal-installation',
                    parent_source_commit=previous['source_commit'],
                    parent_manifest_sha256=parent_manifest_sha256,
                    files={name: payloads[name].sha256 for name in sorted(payloads)})
    raw = (json.dumps(manifest, indent=2, sort_keys=True) + '\n').encode('utf-8')
    _manifest(raw, source_commit)  # The same portable path/collision/complete-OCR contract as delivery.
    # The parent installer verification already validated all unchanged Python,
    # native and OCR inventory. Enforce its required-file rules on replacements.
    for component, present, required in (
            ('audio', bool(audio_files), {'audio/bin/ffmpeg.exe', 'audio/bin/ffprobe.exe', 'audio/LICENSE'}),
            ('citation-runtime', bool(node_files), {'citation-runtime/node.exe', 'citation-runtime/LICENSE'})):
        if present and not required <= set(payloads):
            raise ValueError('Incomplete refreshed ' + component + ' runtime inventory.')
    _check(cancelled)
    return payloads, manifest, raw


def refresh(source, wheel, output, source_commit, *, parent_manifest_sha256,
            audio=None, citations=None, extra_wheelhouse=None, cancelled=lambda: False):
    source, wheel, output = _destination(source, wheel, output)
    payloads, manifest, raw = _plan(source, wheel, source_commit,
        parent_manifest_sha256=parent_manifest_sha256, audio=audio, citations=citations,
        extra_wheelhouse=extra_wheelhouse, cancelled=cancelled)
    output.parent.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix='.private-bundle-', dir=output.parent) as temporary:
        stage = Path(temporary)
        for name, payload in payloads.items():
            target = stage / name
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open('xb') as stream:
                payload.write(stream, cancelled)
        (stage / MANIFEST).write_bytes(raw)
        verify(stage)
        _check(cancelled)
        output.mkdir(mode=0o700)
        for path in stage.iterdir():
            shutil.move(str(path), output / path.name)
    return {'output': str(output), 'source_commit': source_commit,
            'manifest_sha256': hashlib.sha256(raw).hexdigest()}


def refresh_archive(source, wheel, output, source_commit, *, parent_manifest_sha256,
                    audio=None, citations=None, extra_wheelhouse=None,
                    split_ocr_sources=False, source_companion=None, cancelled=lambda: False):
    """Stream a create-only private ZIP, without materializing a second bundle.

    Split mode reuses a verified existing single-entry source companion ZIP.
    Only ocr-corresponding-source.tar is omitted; the manifest still requires it.
    """
    if type(split_ocr_sources) is not bool or not callable(cancelled):
        raise ValueError('Choose an explicit archive split mode and a cancellation callback.')
    if split_ocr_sources != (source_companion is not None):
        raise ValueError('Split archive mode requires the existing OCR source companion ZIP; unsplit mode does not use one.')
    _check(cancelled)
    source, wheel, output = _destination(source, wheel, output)
    if output.suffix.casefold() != '.zip':
        raise ValueError('Choose a new .zip output filename.')
    payloads, manifest, raw = _plan(source, wheel, source_commit,
        parent_manifest_sha256=parent_manifest_sha256, audio=audio, citations=citations,
        extra_wheelhouse=extra_wheelhouse, cancelled=cancelled)
    if max(payload.size for payload in payloads.values()) > MAX_FILE or sum(
            payload.size for payload in payloads.values()) + len(raw) > MAX_TOTAL:
        raise ValueError('Refreshed bundle exceeds the reviewed delivery ZIP size limit.')
    companion = local(source_companion, exists=True) if source_companion is not None else None
    source_expected = {PREFIX + SOURCES: manifest['files'][SOURCES]}
    companion_verified = _verify_archive(companion, source_expected, cancelled) if companion is not None else None
    chosen = {name: payload for name, payload in payloads.items() if not (split_ocr_sources and name == SOURCES)}
    chosen[MANIFEST] = _Payload(raw)
    expected = {PREFIX + name: payload.sha256 for name, payload in chosen.items()}
    output.parent.mkdir(parents=True, exist_ok=True)
    parents = _directories(output.parent)
    parent_fd = os.open(output.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW) if os.name != 'nt' else None
    stage = stage_identity = None
    try:
        descriptor, temporary = tempfile.mkstemp(prefix='.private-archive-', suffix='.zip', dir=output.parent)
        stage = Path(temporary)
        with os.fdopen(descriptor, 'w+b') as target:
            opened = os.fstat(target.fileno())
            stage_identity = _identity(opened)
            if _stamp(regular(stage)) != _stamp(opened):
                raise ValueError('Archive staging file changed before writing.')
            with zipfile.ZipFile(target, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
                for name, payload in sorted(chosen.items()):
                    _check(cancelled)
                    info = zipfile.ZipInfo(PREFIX + name, date_time=(1980, 1, 1, 0, 0, 0))
                    info.create_system = 3
                    info.external_attr = (stat.S_IFREG | 0o644) << 16
                    info.compress_type = zipfile.ZIP_DEFLATED
                    with archive.open(info, 'w', force_zip64=True) as destination:
                        payload.write(destination, cancelled)
            target.flush()
            os.fsync(target.fileno())
        verified = _verify_archive(stage, expected, cancelled)
        if companion is not None and _verify_archive(companion, source_expected, cancelled) != companion_verified:
            raise ValueError('OCR source companion changed during archive refresh.')
        _check(cancelled)
        _unchanged_directories(parents)
        if _stamp(regular(stage)) != verified['_verified_stamp']:
            raise ValueError('Refreshed archive changed after verification.')
        if companion is not None and _stamp(regular(companion)) != companion_verified['_verified_stamp']:
            raise ValueError('OCR source companion changed before publication.')
        # Existing delivery publication uses Windows no-replace rename or Linux
        # renameat2(RENAME_NOREPLACE), valid for a file as well as a directory.
        _publish(stage, output, parent_fd)
        stage = None
        if parent_fd is not None:
            os.fsync(parent_fd)
        application = {key: value for key, value in verified.items() if key != '_verified_stamp'}
        application.update(path=str(output), reused=False)
        archives = {'application': application}
        if companion is not None:
            archives['sources'] = {key: value for key, value in companion_verified.items() if key != '_verified_stamp'}
            archives['sources'].update(path=str(companion), reused=True)
        return {'output': str(output), 'source_commit': source_commit,
                'manifest_sha256': hashlib.sha256(raw).hexdigest(), 'manifest_bytes': len(raw),
                'manifest_payload_files': len(manifest['files']), 'archive_prefix': PREFIX,
                'archives': archives, 'split_ocr_sources': split_ocr_sources,
                'both_archives_required': split_ocr_sources,
                'native_execution': 'NOT_RUN', 'model_inference': 'NOT_RUN'}
    finally:
        try:
            if stage is not None and stage_identity is not None:
                try:
                    info = (os.stat(stage.name, dir_fd=parent_fd, follow_symlinks=False)
                            if parent_fd is not None else stage.lstat())
                except FileNotFoundError:
                    info = None
                # The open descriptor identifies our file. Never unlink a path
                # another operation replaced, including a symlink/reparse point.
                if (info is not None and stat.S_ISREG(info.st_mode)
                        and not getattr(info, 'st_file_attributes', 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT
                        and _identity(info) == stage_identity):
                    if parent_fd is not None:
                        os.unlink(stage.name, dir_fd=parent_fd)
                    else:
                        stage.unlink()
        finally:
            if parent_fd is not None:
                os.close(parent_fd)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for argument in ('source', 'wheel', 'output', 'source-commit', 'parent-manifest-sha256'):
        parser.add_argument('--' + argument, required=True)
    parser.add_argument('--audio')
    parser.add_argument('--citations')
    parser.add_argument('--extra-wheelhouse')
    parser.add_argument('--archive', action='store_true', help='Stream a ZIP directly without a second unpacked bundle')
    parser.add_argument('--source-companion', help='Reuse this verified OCR Sources ZIP; only for --archive split delivery')
    args = parser.parse_args()
    if args.source_companion and not args.archive:
        parser.error('--source-companion requires --archive.')
    options = dict(parent_manifest_sha256=args.parent_manifest_sha256,
                   audio=args.audio, citations=args.citations, extra_wheelhouse=args.extra_wheelhouse)
    if args.archive:
        options.update(split_ocr_sources=args.source_companion is not None, source_companion=args.source_companion)
    operation = refresh_archive if args.archive else refresh
    print(json.dumps(operation(args.source, args.wheel, args.output, args.source_commit, **options)))


if __name__ == '__main__':
    main()
