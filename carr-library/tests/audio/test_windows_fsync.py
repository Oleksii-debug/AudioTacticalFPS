"""Exercise the Windows CRT flush contract on every host.

Windows rejects fsync on read-only regular-file descriptors. Linux accepts
them, so the portability regression must enforce the stricter kernel boundary
instead of accepting an unrelated successful Linux round-trip.
"""
import errno
import os
from pathlib import Path
import stat

import pytest

from carr_library.audio.backup import backup_project, restore_project
from carr_library.audio.jobs import publish_new
from carr_library.ui.audio_studio import StudioController


def windows_flush_contract(monkeypatch):
    original = os.fsync
    flushed = []

    def strict_fsync(descriptor):
        info = os.fstat(descriptor)
        if stat.S_ISREG(info.st_mode):
            if os.name == 'posix':
                import fcntl
                mode = fcntl.fcntl(descriptor, fcntl.F_GETFL) & os.O_ACCMODE
                if mode == os.O_RDONLY:
                    raise OSError(errno.EBADF, 'Windows cannot fsync a read-only file descriptor')
            # On Windows, the real os.fsync below enforces this same condition.
            flushed.append((info.st_dev, info.st_ino))
        return original(descriptor)

    monkeypatch.setattr(os, 'fsync', strict_fsync)
    return flushed


@pytest.fixture
def saved_project(tmp_path):
    root = tmp_path / 'render'
    root.mkdir()
    controller = StudioController(private_root=tmp_path / 'private')
    controller.new('Synthetic text for portable flush verification.', title='Flush verification')
    controller.configure(output_dir=root)
    project = tmp_path / 'project.json'
    controller.save(project)
    controller.draft.replace_literal('Synthetic', 'Revised synthetic')
    controller.save_recovery()
    return project, root


def test_publication_flushes_before_link_with_windows_descriptor_rules(tmp_path, monkeypatch):
    source, target = tmp_path / 'staged.wav', tmp_path / 'published.wav'
    content = b'Synthetic generated bytes; not a voice recording.'
    source.write_bytes(content)
    flushed = windows_flush_contract(monkeypatch)
    original_link = os.link

    def checked_link(source_path, target_path):
        info = Path(source_path).stat()
        assert (info.st_dev, info.st_ino) in flushed, 'Publication preceded a successful file flush.'
        return original_link(source_path, target_path)

    monkeypatch.setattr(os, 'link', checked_link)
    publish_new(source, target)
    assert source.read_bytes() == content == target.read_bytes()
    with pytest.raises(FileExistsError):
        publish_new(source, target)
    assert target.read_bytes() == content


def test_snapshot_flush_is_compatible_with_windows(saved_project, tmp_path, monkeypatch):
    project, root = saved_project
    original = project.read_bytes()
    flushed = windows_flush_contract(monkeypatch)
    target = tmp_path / 'snapshot.zip'
    result = backup_project(project, target, project_dir=root)
    assert result['files'] == 2 and target.is_file()
    info = target.stat()
    assert (info.st_dev, info.st_ino) in flushed
    assert project.read_bytes() == original


def test_relocated_restore_flush_is_compatible_with_windows(saved_project, tmp_path, monkeypatch):
    project, root = saved_project
    archive = tmp_path / 'snapshot.zip'
    backup_project(project, archive, project_dir=root)
    flushed = windows_flush_contract(monkeypatch)
    result = restore_project(archive, tmp_path / 'restored')
    assert result['recovery_relocated'] is True
    restored = Path(result['project_file'])
    for path in (restored, restored.with_name('project.json.recovery.json'),
                 Path(result['directory']) / 'restore-manifest.json'):
        info = path.stat()
        assert (info.st_dev, info.st_ino) in flushed
    reopened = StudioController(private_root=tmp_path / 'new-private')
    reopened.open(restored)
    reopened.recover()
    assert reopened.script.startswith('Revised synthetic')


def test_file_flush_failure_prevents_publication(tmp_path, monkeypatch):
    source, target = tmp_path / 'staged.wav', tmp_path / 'output.wav'
    source.write_bytes(b'Synthetic output')

    def failed_flush(descriptor):
        raise OSError(errno.EIO, 'Synthetic device flush failure')

    monkeypatch.setattr(os, 'fsync', failed_flush)
    with pytest.raises(OSError, match='flush failure'):
        publish_new(source, target)
    assert not target.exists()
    assert source.read_bytes() == b'Synthetic output'
