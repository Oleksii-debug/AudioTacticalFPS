"""Prepare a private copy of the reviewed V4.3 worker; never redistribute it.

Reuses PR135's ASR-03 correction. This is a narrow source transformation, not an
engine installer or completion of the supplied worker's remaining integration.
"""
import argparse
import ast
import hashlib
import importlib.util
import os
from pathlib import Path
import tempfile
from types import SimpleNamespace

SOURCE_BYTES = 37_974
SOURCE_SHA256 = "1df2a1694b35bdf69dab614f91f1e8dea99716dfb039182ef5b83ca5ccb46ec9"


def _one(nodes, kind, name):
    matches = [node for node in nodes if isinstance(node, kind) and node.name == name]
    if len(matches) != 1:
        raise ValueError("Unexpected reviewed worker structure")
    return matches[0]


def prepare(raw: bytes) -> bytes:
    if (type(raw) is not bytes or len(raw) != SOURCE_BYTES
            or hashlib.sha256(raw).hexdigest() != SOURCE_SHA256):
        raise ValueError("Unreviewed worker revision")
    source = raw.decode("utf-8")
    tree = ast.parse(source)
    retry = _one(tree.body, ast.FunctionDef, "_v43_settings_attempts")
    worker = _one(tree.body, ast.ClassDef, "Worker")
    transcribe = _one(worker.body, ast.FunctionDef, "transcribe_one")
    fallback = next((node for node in transcribe.body if isinstance(node, ast.Try)), None)
    if (fallback is None or len(fallback.body) != 1 or len(fallback.handlers) != 1
            or not isinstance(fallback.handlers[0].type, ast.Name)
            or fallback.handlers[0].type.id != "TypeError"
            or fallback.orelse or fallback.finalbody
            or not isinstance(fallback.body[0], ast.Assign)
            or not isinstance(fallback.body[0].value, ast.Call)
            or not isinstance(fallback.body[0].value.func, ast.Attribute)
            or fallback.body[0].value.func.attr != "transcribe"
            or not isinstance(fallback.body[0].value.func.value, ast.Attribute)
            or fallback.body[0].value.func.value.attr != "model"
            or not isinstance(fallback.body[0].value.func.value.value, ast.Name)
            or fallback.body[0].value.func.value.value.id != "self"):
        raise ValueError("Unexpected reviewed recognition fallback")
    if (not retry.body or len(retry.args.args) != 1 or retry.args.args[0].arg != "base"
            or retry.args.posonlyargs or retry.args.kwonlyargs
            or retry.args.vararg or retry.args.kwarg or retry.args.defaults):
        raise ValueError("Unexpected reviewed recognition settings")

    lines = source.splitlines(keepends=True)
    statement = fallback.body[0]
    call_lines = lines[statement.lineno - 1:statement.end_lineno]
    if (not call_lines or statement.col_offset <= fallback.col_offset
            or not call_lines[0].startswith(" " * statement.col_offset)):
        raise ValueError("Unexpected reviewed recognition indentation")
    # Keep the supplied call, argument spelling, continuation lines, comments
    # and literal bytes. Only its first-line indentation leaves the removed try.
    # ast.unparse would make generated bytes depend on the preparer's Python.
    call_lines[0] = " " * fallback.col_offset + call_lines[0][statement.col_offset:]
    newline = "\r\n" if lines[retry.body[0].lineno - 1].endswith("\r\n") else "\n"
    edits = [
        (retry.body[0].lineno, retry.end_lineno,
         " " * (retry.col_offset + 4) + 'return [("original", dict(base))]' + newline),
        (fallback.lineno, fallback.end_lineno, "".join(call_lines)),
    ]
    for first, last, replacement in sorted(edits, reverse=True):
        lines[first - 1:last] = [replacement]
    result = "".join(lines)
    compile(result, "<prepared-worker>", "exec")
    return result.encode("utf-8")


def _read_source(path):
    # Read only enough to reject any larger input before parsing or importing.
    with Path(path).open("rb") as stream:
        return stream.read(SOURCE_BYTES + 1)


def _publish_private(candidate, destination):
    """Fsync a private stage, then publish exclusively; never replace a file."""
    destination = Path(destination)
    descriptor, name = tempfile.mkstemp(prefix=".asr-prepared-", suffix=".part",
                                        dir=destination.parent)
    staged = Path(name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(candidate)
            stream.flush()
            os.fsync(stream.fileno())
        # A hard link is an atomic no-overwrite publication. If the selected
        # filesystem cannot provide it, fail without a permissive overwrite.
        os.link(staged, destination)
    finally:
        staged.unlink(missing_ok=True)


def checks(path: Path):
    """Synthetic checks for an already authorized private temporary source."""
    spec = importlib.util.spec_from_file_location("checked_worker", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    settings = {"language": "auto", "multilingual": True, "beam_size": 5,
                "vad_filter": True, "condition_on_previous_text": True}
    attempts = module._v43_settings_attempts(settings)
    verdicts = {"no_implicit_language_or_settings_retry":
                attempts == [("original", settings)]}
    worker = module.Worker.__new__(module.Worker)
    worker.load_model_if_needed = lambda settings: None
    item = {"path": "synthetic.wav", "group": "test", "relative": "synthetic.wav"}
    calls = []

    def unsupported(path, **kwargs):
        calls.append(kwargs)
        if kwargs.get("multilingual"):
            raise TypeError("synthetic unsupported option")
        return iter([]), SimpleNamespace(language="uk", duration=0)

    worker.model = SimpleNamespace(transcribe=unsupported)
    try:
        worker.transcribe_one(item, settings)
    except TypeError:
        rejected = True
    else:
        rejected = False
    verdicts["unsupported_multilingual_fails_without_retry"] = rejected and len(calls) == 1
    calls.clear()

    def supported(path, **kwargs):
        calls.append(kwargs)
        return iter([]), SimpleNamespace(language="uk", duration=0)

    worker.model = SimpleNamespace(transcribe=supported)
    text, detected, _, meta = worker.transcribe_one(item, settings)
    verdicts["auto_detection_keeps_language_and_empty_result"] = (
        text == "" and detected == "uk" and meta["selected_language"] == "auto"
        and len(calls) == 1 and calls[0]["language"] is None)
    return verdicts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--output", type=Path,
                        help="New file in an authorized private directory outside public source.")
    args = parser.parse_args()
    if not args.verify and not args.output:
        parser.error("select --verify and/or --output")
    raw = _read_source(args.source)
    candidate = prepare(raw)
    print("source_sha256=" + hashlib.sha256(raw).hexdigest())
    print("candidate_sha256=" + hashlib.sha256(candidate).hexdigest())
    if args.verify:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name, data in [("baseline", raw), ("candidate", candidate)]:
                path = root / (name + ".py")
                path.write_bytes(data)
                verdicts = checks(path)
                for test, passed in verdicts.items():
                    print(name, test, "PASS" if passed else "FAIL")
                if name == "candidate" and not all(verdicts.values()):
                    raise SystemExit(1)
    if args.output:
        _publish_private(candidate, args.output)


if __name__ == "__main__":
    main()
